def detect_niche(handle, bio_text, website_content):
    """
    Simple heuristic niche detection.
    Returns niche key or 'restaurant' as default.
    """
    text = f"{bio_text} {website_content}".lower()

    niche_keywords = {
        "restaurant": ["restaurant", "food", "kitchen", "chef", "dining", "cuisine", "menu", "reservation", "table", "wine", "cocktail", "bar", "lounge", "eat", "taste"],
        "fashion": ["fashion", "clothing", "apparel", "streetwear", "boutique", "label", "brand", "wear", "threads", "garments", "collection", "drop", "lookbook", "designer", "outfit", "style"],
        "hospitality": ["hotel", "guesthouse", "lodge", "accommodation", "stay", "retreat", "spa", "resort", "bnb", "booking", "room", "suite", "getaway"],
        "beauty": ["beauty", "aesthetic", "skincare", "clinic", "salon", "spa", "treatment", "facial", "makeup", "cosmetic", "laser", "botox", "wellness"],
        "events": ["events", "venue", "party", "nightlife", "club", "festival", "concert", "wedding", "corporate", "launch", "celebration"],
        "musician": ["music", "artist", "rapper", "producer", "dj", "band", "hip hop", "rap", "amapiano", "gospel", "r&b", "singer", "songwriter", "mixtape", "album", "single"],
        "clothing_brand": ["clothing", "fashion", "streetwear", "boutique", "label", "brand", "wear", "threads", "garments", "collection", "drop", "lookbook"]
    }

    scores = {}
    for niche, keywords in niche_keywords.items():
        scores[niche] = sum(1 for kw in keywords if kw in text)

    if scores:
        best_niche = max(scores, key=scores.get)
        if scores[best_niche] > 0:
            return best_niche

    return "restaurant"  # Default to highest-value niche


def get_niche_config(niche_key):
    return NICHES.get(niche_key, NICHES["restaurant"])
